/**
 * FlightGear のアニメーション XML の座標系。
 *
 * `.ac` とも当方の系とも違う。**後方 +X、右 +Y、上 +Z。**
 *
 * この対応は機体 2 機で別々に突き合わせて確かめた。推測ではない。
 *
 * F/A-18C。`.ac` の AileronLeft が Z +3.742..+5.436 にあり、XML のヒンジが
 * y1 = −3.74241、y2 = −5.42703。よって xml.y = −ac.z。
 *
 * F-16。XML の LeftUpperFlap の center が (1.54, −2.35, 0.12) で、`.ac` の
 * LeftLowerFlap が X 1.33..2.18 / Y 0.05..0.20 / Z 1.07..3.58。x はそのまま、
 * y は符号を変えて ac.z、z は ac.y。ラダーの center (4.915, 0, 2.095) と
 * `.ac` の Rudder（X 4.31..5.89 / Y 1.15..3.03 / Z ≈ 0）でも成り立つ。
 *
 * `.ac` 側の系（機首 −X、上 +Y、左 +Z）も 2 機で一致していた。F-16 では
 * ピトー管が X −8.41..−7.64、垂直尾翼が X +2.81..+5.89 / Y +1.15..+3.19、
 * そして航法灯が WingRedPosLight を Z +4.49..+4.59、WingGreenPosLight を
 * Z −4.60..−4.50 に置いている。**赤が左舷・緑が右舷という灯火の約束から
 * +Z が左と決まる。**
 */

/** XML 座標を当方の座標（機首 −Z、上 +Y、右 +X）へ */
export function xmlToWorld(v) {
  return [v[1], v[2], v[0]]
}

/** XML 座標を .ac の座標へ。テストが舵面の境界と突き合わせるのに使う */
export function xmlToAc(v) {
  return [v[0], v[2], -v[1]]
}
